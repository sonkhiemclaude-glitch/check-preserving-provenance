"""Baselines from prior provenance-sanitisation work, adapted to agentic graphs
.

  suppress_all : keep node types and relations, remove every value and timing
  modhide      : module hiding in the style of Davidson et al. (module privacy)
  abstract     : structural abstraction in the style of user views / PROV abstraction

These are the simplified, fully specified adaptations evaluated here.
They are NOT the original systems of the cited works: Davidson et al. hide a
minimum-cost attribute subset achieving Gamma-privacy, and ZOOM/ProvAbs compute
views from user-declared relevant modules. Wrappers for the original systems
are in external_wrappers.py (adapter stubs).

All three are applied after VG (see baselines.registry.build_baseline).
"""
from __future__ import annotations

import pandas as pd

from ..data.schemas import ATTR_CLASS, SUPP, Graph
from ..data.spec import Spec


def suppress_all(g: Graph) -> Graph:
    """Keep node types and relations; replace every value and drop all timing."""
    h = g.copy()
    keep = {"id", "run", "type", "kind", "src", "dst"}
    for tab in ("act", "ent"):
        df = getattr(h, tab)
        for c in df.columns:
            if c not in keep:
                df[c] = SUPP
    h.act = h.act.drop(columns=[c for c in ("start", "end", "seq") if c in h.act.columns])
    for c in h.runs.columns:
        if c != "run":
            h.runs[c] = SUPP
    h.meta.setdefault("ops", []).append("SUPPRESS")
    return h


def modhide(g: Graph, private_types: set, keep_vocab: bool = True) -> Graph:
    """Module privacy in the style of classical workflow-provenance work:
    hide the attributes of private modules and of the data they use or
    generate; keep structure, timing and public modules. With keep_vocab,
    module identity and configuration that lie in the public vocabulary
    (tool, model, temperature) stay visible, as in Davidson et al., who hide
    data attributes rather than module identity."""
    h = g.copy()
    act, ent, e = h.act, h.ent, h.edge
    priv = act["type"].isin(private_types).to_numpy()
    priv_ids = set(act["id"].to_numpy()[priv])
    touched = set(e[(e["kind"] == "used") & e["src"].isin(priv_ids)]["dst"]) | \
        set(e[(e["kind"] == "wasGeneratedBy") & e["dst"].isin(priv_ids)]["src"])
    for c in act.columns:
        if c in ATTR_CLASS and not (keep_vocab and ATTR_CLASS[c] == "vocab"):
            act.loc[priv, c] = SUPP
    em = ent["id"].isin(touched).to_numpy()
    for c in ent.columns:
        if c in ATTR_CLASS:
            ent.loc[em, c] = SUPP
    h.meta.setdefault("ops", []).append("MODHIDE")
    return h


def abstract(g: Graph, spec: Spec, group_types: set, composite: str = "prepare_inputs") -> Graph:
    """Structural abstraction in the style of user views / PROV abstraction:
    per run, collapse the activities of group_types into one composite
    activity, replace all source partitions by one pooled source entity with
    hidden values, and drop entities internal to the group."""
    h = g.copy()
    act, ent, e = h.act, h.ent, h.edge
    grp = act["type"].isin(group_types)
    gact = act[grp]
    gids = set(gact["id"])
    max_id = int(max(act["id"].max(), ent["id"].max())) + 1
    comp_rows, pooled_rows, new_edges = [], [], []
    comp_of_run, pool_of_run = {}, {}
    agg = gact.groupby("run").agg(start=("start", "min"), end=("end", "max"), seq=("seq", "min"))
    for i, (run, row) in enumerate(agg.iterrows()):
        cid = max_id + 2 * i
        pid = max_id + 2 * i + 1
        comp_of_run[run] = cid
        pool_of_run[run] = pid
        r: dict = {c: SUPP for c in act.columns if c in ATTR_CLASS}
        r.update({"id": cid, "run": run, "type": composite, "start": row["start"], "end": row["end"], "seq": row["seq"]})
        comp_rows.append(r)
        p: dict = {c: SUPP for c in ent.columns if c in ATTR_CLASS}
        p.update({"id": pid, "run": run, "type": spec.source_type})
        pooled_rows.append(p)
        new_edges.append({"kind": "used", "src": cid, "dst": pid, "run": run})
    src_ids = set(ent[ent["type"] == spec.source_type]["id"])
    # entities generated by group members
    gen_by_grp = e[(e["kind"] == "wasGeneratedBy") & e["dst"].isin(gids)]
    used_outside = e[(e["kind"] == "used") & ~e["src"].isin(gids)]
    exported = set(gen_by_grp["src"]) & set(used_outside["dst"])
    internal = set(gen_by_grp["src"]) - exported
    drop_ent = internal | src_ids
    keep_e = e[~(e["src"].isin(gids) | e["dst"].isin(gids) | e["src"].isin(drop_ent) | e["dst"].isin(drop_ent))]
    erun = dict(zip(ent["id"], ent["run"]))
    for n in exported:
        new_edges.append({"kind": "wasGeneratedBy", "src": n, "dst": comp_of_run[erun[n]], "run": erun[n]})
    # informedBy edges from outside into the group are redirected to the composite
    inf = e[(e["kind"] == "wasInformedBy") & e["dst"].isin(gids) & ~e["src"].isin(gids)]
    arun = dict(zip(act["id"], act["run"]))
    for s in inf["src"].unique():
        new_edges.append({"kind": "wasInformedBy", "src": s, "dst": comp_of_run[arun[s]], "run": arun[s]})
    h.act = pd.concat([act[~grp], pd.DataFrame(comp_rows)], ignore_index=True)
    h.ent = pd.concat([ent[~ent["id"].isin(drop_ent)], pd.DataFrame(pooled_rows)], ignore_index=True)
    h.edge = pd.concat([keep_e, pd.DataFrame(new_edges)], ignore_index=True)
    h.meta.setdefault("ops", []).append("ABSTRACT")
    return h


